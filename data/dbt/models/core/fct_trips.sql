-- The central fact table: one row per trip, every service (ride, parcel, rental, intercity).
select
    t.id as trip_id,
    t.trip_number,
    t.service,
    t.status,
    t.is_completed,
    t.is_cancelled,
    t.is_no_driver,
    t.cancelled_by,
    t.city_id,
    t.pickup_zone_id,
    t.dropoff_zone_id,
    t.ride_type_id,
    t.rider_id,
    t.driver_id,
    t.request_date,
    t.request_hour,
    t.request_weekday,
    t.requested_at,
    t.payment_method,
    t.payment_status,
    t.surge_multiplier,
    t.surge_multiplier > 1 as was_surge,
    t.estimated_fare,
    t.estimated_distance_km,
    t.actual_distance_km,
    t.seconds_to_assign,
    t.pickup_minutes,
    t.ride_minutes,
    t.pickup_eta_min,
    coalesce(t.fare_total, 0) as fare_total,
    coalesce(t.driver_earning, 0) as driver_earning,
    coalesce(t.platform_commission, 0) as platform_commission,
    coalesce(t.gst_amount, 0) as gst_amount,
    coalesce(t.discount_amount, 0) as discount_amount,
    t.tip_amount,
    t.cancellation_fee,
    t.boost_amount,
    t.fare_offer is not null as was_bid,
    t.offer_adjustment,
    t.sure_ride_minutes is not null as used_sure_ride,
    t.sure_ride_refunded,
    t.ride_pass_applied,
    t.fare_locked,
    t.used_promo,
    t.night_safe,
    t.co2_saved_g,
    t.package_hours,
    t.round_trip,
    t.trip_days,
    t.dispatch_attempts,
    t.dispatch_round,
    len(t.flags) > 0 as was_flagged,
    list_contains(t.flags, 'SOS') as had_sos,
    list_contains(t.flags, 'ROUTE_DEVIATION') as had_route_deviation,
    t.harsh_brakes,
    t.speeding_seconds,
    r.stars as rider_rating_of_driver
from {{ ref('stg_trips') }} t
left join {{ ref('stg_ratings') }} r on r.trip_id = t.id and r.direction = 'RIDER_TO_DRIVER'
